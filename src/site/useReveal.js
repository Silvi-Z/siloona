import { useEffect, useRef } from 'react'

// Lightweight scroll-reveal: adds `.in` once an element enters the viewport.
// No animation library — matches the project's "no unnecessary dependencies" rule.
export function useReveal() {
  const ref = useRef(null)

  useEffect(() => {
    const el = ref.current
    if (!el) return
    const io = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) {
          el.classList.add('in')
          io.unobserve(el)
        }
      },
      { threshold: 0.15 },
    )
    io.observe(el)
    return () => io.disconnect()
  }, [])

  return ref
}
